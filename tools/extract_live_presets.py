#!/usr/bin/env python3
"""Generates client/src/LiveEngine/LiveGroupPresetTable.cs from the AudioGroupPreset assets of
the live client: volume and distance/spread curves of each sound group.

    python3 tools/extract_live_presets.py \\
      --data "<live>/EscapeFromTarkov_Data" \\
      --out client/src/LiveEngine/LiveGroupPresetTable.cs
"""
import argparse
import os
import struct

import UnityPy

GROUPS = ["Gunshots", "Impacts", "Character", "Environment", "Collisions", "Speech", "Distant",
          "Grenades", "Weaponary", "Windows", "Voip", "Lamp", "InteractiveObjects",
          "PropagatedExclusive", "LightOcclusion"]


def curve(raw, pos):
    count = struct.unpack_from("<i", raw, pos)[0]
    pos += 4
    keys = []
    for _ in range(count):
        time, value, in_slope, out_slope = struct.unpack_from("<4f", raw, pos)
        keys.append((time, value, in_slope, out_slope))
        pos += 28
    return keys, pos + 12


def read_preset(raw):
    name_length = struct.unpack_from("<i", raw, 28)[0]
    pos = (32 + name_length + 3) & ~3
    # loadSettingsFromBackend, Type, OverallVolume, SpatialBlend
    volume = struct.unpack_from("<f", raw, pos + 8)[0]
    spread, pos = curve(raw, pos + 16)
    rolloff, pos = curve(raw, pos)
    # AudioSourcePriorityRange, DefaultMaxDistance, betterSourceSettings, poolSettings,
    # Spatialize, then UseSimpleSpatializer, gain, pattern, directivity: OcclusionSourceRadius
    simple = raw[pos + 68] != 0
    radius = struct.unpack_from("<f", raw, pos + 84)[0]
    dynamic = raw[pos + 88] != 0
    hrtf = struct.unpack_from("<5f", raw, pos + 92)
    blend_curve, _ = curve(raw, pos + 112)
    return volume, spread, rolloff, radius, simple, dynamic, hrtf, blend_curve


def cs_curve(keys):
    inner = ", ".join(f"new Keyframe({k[0]:.6g}f, {k[1]:.6g}f, {k[2]:.6g}f, {k[3]:.6g}f)" for k in keys)
    return f"new AnimationCurve({inner})"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()

    env = UnityPy.load(os.path.join(args.data, "resources.assets"))
    found = {}
    for obj in env.objects:
        if obj.type.name != "MonoBehaviour":
            continue
        raw = obj.get_raw_data()
        name_length = struct.unpack_from("<i", raw, 28)[0] if len(raw) > 32 else 0
        if not 0 < name_length < 64:
            continue
        name = raw[32:32 + name_length].decode("utf8", "replace")
        if name in GROUPS and len(raw) > 2000:
            found[name] = read_preset(raw)
    missing = [g for g in GROUPS if g not in found]
    if missing:
        raise SystemExit(f"presets not found: {missing}")

    lines = [
        "// Generated by tools/extract_live_presets.py from the live client: do not edit.",
        "using System.Collections.Generic;",
        "using UnityEngine;",
        "",
        "namespace SoundEngineBackport.LiveEngine",
        "{",
        "    internal static class LiveGroupPresetTable",
        "    {",
        "        internal sealed class Entry",
        "        {",
        "            public float OverallVolume;",
        "            public float OcclusionSourceRadius;",
        "            public bool UseSimpleSpatializer;",
        "            public bool DynamicHrtf;",
        "            public float HrtfMinDistance;",
        "            public float HrtfMinHeight;",
        "            public float HrtfMinAngle;",
        "            public float HrtfIntensity;",
        "            public float HrtfSmoothSpeed;",
        "            public AnimationCurve Spread;",
        "            public AnimationCurve Rolloff;",
        "        }",
        "",
        "        public static readonly Dictionary<string, Entry> Groups = new Dictionary<string, Entry>",
        "        {",
    ]
    for group in GROUPS:
        volume, spread, rolloff, radius, simple, dynamic, hrtf, blend_curve = found[group]
        if dynamic and not simple and [tuple(round(v, 3) for v in key) for key in blend_curve] != [(0, 0, 0, 0), (1, 1, 0, 0)]:
            raise SystemExit(f"{group}: the plugin assumes a smoothstep HRTF curve, found {blend_curve}")
        lines += [
            f'            ["{group}"] = new Entry',
            "            {",
            f"                OverallVolume = {volume:.6g}f,",
            f"                OcclusionSourceRadius = {radius:.6g}f,",
            f"                UseSimpleSpatializer = {str(simple).lower()},",
            f"                DynamicHrtf = {str(dynamic).lower()},",
            f"                HrtfMinDistance = {hrtf[0]:.6g}f,",
            f"                HrtfMinHeight = {hrtf[1]:.6g}f,",
            f"                HrtfMinAngle = {hrtf[2]:.6g}f,",
            f"                HrtfIntensity = {hrtf[3]:.6g}f,",
            f"                HrtfSmoothSpeed = {hrtf[4]:.6g}f,",
            f"                Spread = {cs_curve(spread)},",
            f"                Rolloff = {cs_curve(rolloff)},",
            "            },",
        ]
    lines += ["        };", "    }", "}", ""]
    with open(args.out, "w") as stream:
        stream.write("\n".join(lines))
    print(f"{args.out}: {len(found)} groups")


if __name__ == "__main__":
    main()
